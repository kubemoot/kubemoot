// Generates src/lib/types/bus.ts, the TypeScript types of the Kubemoot bus contract,
// from the JSON Schema files in operator/pkg/bus/schema. Run it with npm run gen:bus
// after changing the schema. The file records the schema digest; the operator's
// contract test fails when the digest no longer matches the schema.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, '../../operator/pkg/bus/schema');
const output = join(here, '../src/lib/types/bus.ts');

/**
 * The SHA-256 of the files, each as its name, a NUL, its content and a NUL, in name
 * order, in hex: the digest operator/pkg/bus/internal/schemaset computes.
 * @param {Map<string, Buffer>} files
 */
export function digest(files) {
	const hash = createHash('sha256');
	for (const name of [...files.keys()].sort()) {
		hash.update(name);
		hash.update('\0');
		hash.update(files.get(name) ?? Buffer.alloc(0));
		hash.update('\0');
	}
	return hash.digest('hex');
}

/**
 * A schema with one definition per payload file, so a single compile emits every
 * type once.
 * @param {string[]} names the JSON Schema file names
 * @returns {import('json-schema-to-typescript').JSONSchema}
 */
export function rootSchema(names) {
	/** @type {Record<string, { $ref: string }>} */
	const definitions = {};
	for (const name of names) {
		definitions[name.replace(/\.json$/, '')] = { $ref: name };
	}
	return { title: 'KubemootBus', type: 'object', definitions };
}

/**
 * A schema file without the goJSONSchema keywords, which only steer the Go generator.
 * @param {Buffer | string} data
 */
export function withoutGoHints(data) {
	return JSON.stringify(JSON.parse(String(data)), (key, value) =>
		key === 'goJSONSchema' ? undefined : value
	);
}

/**
 * The generated source without the empty interface of the root schema.
 * @param {string} ts
 */
export function withoutRoot(ts) {
	return ts.replace(/\nexport interface KubemootBus \{\}\n/, '\n');
}

function readSchemaDir() {
	const files = new Map();
	for (const name of readdirSync(schemaDir)) {
		files.set(name, readFileSync(join(schemaDir, name)));
	}
	return files;
}

async function main() {
	const files = readSchemaDir();
	const names = [...files.keys()].filter((n) => n.endsWith('.json')).sort();
	const banner = [
		'// Code generated by json-schema-to-typescript from operator/pkg/bus/schema, DO NOT EDIT.',
		`// Schema digest: ${digest(files)}`,
		'// Regenerate with: npm run gen:bus'
	].join('\n');
	const ts = await compile(rootSchema(names), 'KubemootBus', {
		bannerComment: banner,
		cwd: schemaDir,
		additionalProperties: false,
		unreachableDefinitions: true,
		declareExternallyReferenced: true,
		style: { useTabs: true, singleQuote: true, printWidth: 100 },
		$refOptions: {
			resolve: {
				file: {
					read: (/** @type {{ url: string }} */ file) => withoutGoHints(readFileSync(file.url))
				}
			}
		}
	});
	writeFileSync(output, withoutRoot(ts));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	await main();
}
