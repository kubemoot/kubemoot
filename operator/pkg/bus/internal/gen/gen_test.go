// kwType is the JSON Schema type keyword.
const kwType = "type"

func TestPrepareForGoMakesScalarsValuesAndIntegersInt64(t *testing.T) {
	doc := map[string]any{
		kwType: "object",
		"properties": map[string]any{
			"name":  map[string]any{kwType: "string"},
			"count": map[string]any{kwType: "integer"},
			"list":  map[string]any{kwType: "array", "items": map[string]any{kwType: "integer"}},
			"ref":   map[string]any{"$ref": "other.json"},
			"meta":  map[string]any{"$ref": "m.json", extension: map[string]any{kwType: "map[string]any"}},
		},
	}
	got := PrepareForGo(doc)
	props := got["properties"].(map[string]any)
	want := map[string]any{
		"name":  map[string]any{"pointer": false},
		"count": map[string]any{kwType: "int64", "pointer": false},
		"meta":  map[string]any{kwType: "map[string]any"},
	}
	for name, ext := range want {
		if !reflect.DeepEqual(props[name].(map[string]any)[extension], ext) {
			t.Errorf("%s: got %v, want %v", name, props[name].(map[string]any)[extension], ext)
		}
	}
	if _, ok := props["ref"].(map[string]any)[extension]; ok {
		t.Error("a reference keeps go-jsonschema's pointer")
	}
	items := props["list"].(map[string]any)["items"].(map[string]any)
	if !reflect.DeepEqual(items[extension], map[string]any{kwType: "int64"}) {
		t.Errorf("array items: %v", items[extension])
	}
	if _, ok := doc["properties"].(map[string]any)["name"].(map[string]any)[extension]; ok {
		t.Error("PrepareForGo changed its input")
	}
}

func TestPropertyOrdersFollowTheFile(t *testing.T) {
	data := []byte(`{"title": "Outer", "properties": {"zeta": {"type": "string"}, "alpha": {
	  "title": "Inner", "type": "object", "properties": {"b": {}, "a": {}}}},
	  "definitions": {"D": {"title": "Def", "properties": {"y": {}, "x": {}}}}, "enum": [1, 2]}`)
	got, err := PropertyOrders(data)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]string{"Outer": {"zeta", "alpha"}, "Inner": {"b", "a"}, "Def": {"y", "x"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for _, bad := range []string{`{"properties": []}`, `{"title": 1}`, `{`} {
		if _, err := PropertyOrders([]byte(bad)); err == nil {
			t.Errorf("%s: no error", bad)
		}
	}
}

func TestReorderFieldsFollowsTheSchema(t *testing.T) {
	src := "type Thing struct {\n" +
		"\t// A is a.\n\tA string `json:\"a,omitempty\"`\n\n" +
		"\tB string `json:\"b\"`\n\n" +
		"\tC string `json:\"c\"`\n}\n\ntype Other struct {\n\tZ int `json:\"z\"`\n}\n"
	got := ReorderFields(src, map[string][]string{"Thing": {"c", "a"}, "Missing": {"x"}})
	want := "type Thing struct {\n" +
		"\tC string `json:\"c\"`\n\n" +
		"\t// A is a.\n\tA string `json:\"a,omitempty\"`\n\n" +
		"\tB string `json:\"b\"`\n}\n\ntype Other struct {\n\tZ int `json:\"z\"`\n}\n"
	if got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
	if unchanged := ReorderFields("type Thing struct {", map[string][]string{"Thing": {"a"}}); unchanged != "type Thing struct {" {
		t.Fatalf("an unterminated struct changed: %q", unchanged)
	}
}

func TestDecorateAddsTheDigestAndVersion(t *testing.T) {
	set := &schemaset.Set{Version: "1.2.3", Digest: "abc"}
	out, err := decorate([]byte("// Code generated by x, DO NOT EDIT.\n\npackage bus\n"), set)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"// Schema digest: abc\n", `const ContractVersion = "1.2.3"`} {
		if !strings.Contains(string(out), want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if _, err := decorate([]byte("no newline"), set); err == nil {
		t.Error("output without a header line was accepted")
	}
}

func TestWriteForGoLeavesCompositionsOut(t *testing.T) {
	set, err := schemaset.Load("../../schema")
	if err != nil {
		t.Fatal(err)
	}
	files, err := writeForGo(set, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != len(set.Names())-1 {
		t.Fatalf("wrote %d of %d schemas, want all but stream-event.json", len(files), len(set.Names()))
	}
	for _, f := range files {
		if strings.HasSuffix(f, "/stream-event.json") {
			t.Fatal("the allOf composition was written")
		}
	}
	orders, err := propertyOrders(set)
	if err != nil {
		t.Fatal(err)
	}
	if got := orders["StreamEventBase"]; len(got) == 0 || got[0] != "type" {
		t.Fatalf("StreamEventBase order %v, want type first", got)
	}
}
