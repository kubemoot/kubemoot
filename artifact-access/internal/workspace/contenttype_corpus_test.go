package workspace

import (
	"encoding/json"
	"math/rand"
	"os"
	"strings"
	"testing"
)

// The generated corpus is the randomized half of the check that the Go and Java detectors agree:
// seeded text built from fragments that sit on the edges of the rules (table rows, YAML
// features, quotes, odd spaces). Go decides each type and writes it to
// test/fixtures/result-types-generated.json; agent-runtime's ResultTypeTest decides the same
// inputs and must give the same types. Regenerate with UPDATE_RESULT_CORPUS=1 go test ./internal/workspace.
const (
	corpusPath  = "../../../test/fixtures/result-types-generated.json"
	corpusSize  = 1500
	corpusSeed  = 20261115
	updateEnv   = "UPDATE_RESULT_CORPUS"
	maxFragment = 5
)

// corpusFamilies group fragments that belong to one format, so most generated inputs are close to
// a real format and the rest of the rules (the edges) are reached by mixing a stray line in.
var corpusFamilies = [][]string{
	{"a: 1", "b: [1, 2]", "- x", "- name: a", "  nested: true", "---", "...", "key:", ": x", "# comment",
		"a: &x 1", "b: *x", "c: *nope", "d: !!int abc", "e: !!str 5", "f: 'quoted: value'", "g: \"a, b\"", "a: b: c"},
	{"| a | b |", "|---|---|", "| :--- | ---: |", "|a|b|", "| 1 | 2 |"},
	{"NAME   READY   STATUS", "NAME", "name   ready", "foo    1/1     Running", "bar    0/1     Pending"},
	{"a,b", "1,2", "\"q,r\",3", "a,\"b", "x\"y,1", ",,", "a,b,c", "x,y"},
	{`{"k": 1}`, `[1, 2]`, `[`, `{"a":`, `"s"`, "42", "[null]", "false", `{"items": []}`},
	{"text with spaces", "Error: failed", "Error: failed: really", "\u00e9,\u00fc", "\u540d\u524d: \u5024", "a:b"},
}

// corpusStray are lines that change what the rules see when mixed into a family.
var corpusStray = []string{"\t", " ", "\u00a0", "\u2003x", "\u001c", "\u000b", "\u0085", "\ufeff", "", "x: y", "p,q"}

type corpusCase struct {
	Input string `json:"input"`
	Type  string `json:"type"`
}

type corpusFile struct {
	Description string       `json:"description"`
	Seed        int64        `json:"seed"`
	Cases       []corpusCase `json:"cases"`
}

func generateCorpus() []corpusCase {
	rng := rand.New(rand.NewSource(corpusSeed))
	out := make([]corpusCase, 0, corpusSize)
	for len(out) < corpusSize {
		family := corpusFamilies[rng.Intn(len(corpusFamilies))]
		n := 1 + rng.Intn(maxFragment)
		lines := make([]string, n)
		for i := range lines {
			if rng.Intn(6) == 0 {
				lines[i] = corpusStray[rng.Intn(len(corpusStray))]
			} else {
				lines[i] = family[rng.Intn(len(family))]
			}
		}
		sep := "\n"
		if rng.Intn(8) == 0 {
			sep = "\r\n"
		}
		in := strings.Join(lines, sep)
		if rng.Intn(2) == 0 {
			in += sep
		}
		out = append(out, corpusCase{Input: in, Type: DetectContentType([]byte(in))})
	}
	return out
}

func TestDetectContentTypeGeneratedCorpus(t *testing.T) {
	want := generateCorpus()
	if os.Getenv(updateEnv) != "" {
		raw, err := json.MarshalIndent(corpusFile{
			Description: "Seeded random inputs and the type artifact-access decides for each. Generated by contenttype_corpus_test.go; agent-runtime's ResultTypeTest must decide the same types.",
			Seed:        corpusSeed, Cases: want,
		}, "", " ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(corpusPath, append(raw, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	raw, err := os.ReadFile(corpusPath)
	if err != nil {
		t.Fatal(err)
	}
	var got corpusFile
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatal(err)
	}
	if len(got.Cases) != len(want) {
		t.Fatalf("the corpus has %d cases, the generator makes %d; regenerate with %s=1", len(got.Cases), len(want), updateEnv)
	}
	for i, c := range got.Cases {
		if c.Input != want[i].Input || c.Type != want[i].Type {
			t.Fatalf("case %d differs from the generator (or the detector changed); regenerate with %s=1", i, updateEnv)
		}
	}
}
